"""PostgreSQL backend.

Wraps a ``psycopg`` connection so the rest of ``api/`` can keep using
``?``-placeholder SQL and both ``row[0]`` / ``row["col"]`` access patterns.

Responsibilities of the wrapper:
- translate ``?`` placeholders to ``%s`` and escape literal ``%`` on every
  ``execute``/``executemany`` (see :func:`api.db.base.translate_sql`);
- materialize fetched rows as :class:`api.db.base.DbRow` so positional and
  name-based access both work;
- emulate ``executescript`` by splitting the script into statements
  (:func:`api.db.base.split_script`);
- adapt SQLite-style DDL (``INTEGER PRIMARY KEY AUTOINCREMENT``) to the
  Postgres identity-column syntax within ``executescript``.
"""

from __future__ import annotations

import re
from typing import TYPE_CHECKING, Any

from api.config import settings
from api.db.base import DbRow, split_script, translate_sql

if TYPE_CHECKING:
    from collections.abc import Iterable, Sequence

    import psycopg


_AUTOINCREMENT_RE = re.compile(
    r"\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b",
    re.IGNORECASE,
)


def _adapt_ddl(script: str) -> str:
    """Rewrite SQLite autoincrement DDL to Postgres identity columns."""

    return _AUTOINCREMENT_RE.sub(
        "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
        script,
    )


class _PgCursor:
    """Adapter cursor wrapping a psycopg cursor, returning :class:`DbRow`."""

    def __init__(self, cur: "psycopg.Cursor") -> None:
        self._cur = cur

    @property
    def description(self) -> Any:
        return self._cur.description

    def _column_names(self) -> list[str]:
        if self._cur.description is None:
            return []
        return [col[0] for col in self._cur.description]

    def _wrap(self, row: Any) -> DbRow | None:
        if row is None:
            return None
        return DbRow(tuple(row), self._column_names())

    def execute(
        self,
        operation: str,
        parameters: "Sequence[Any] | dict[str, Any] | None" = None,
    ) -> "_PgCursor":
        self._cur.execute(translate_sql(operation, escape_percent=True), parameters or ())
        return self

    def executemany(
        self,
        operation: str,
        seq_of_parameters: "Iterable[Sequence[Any]]",
    ) -> "_PgCursor":
        translated = translate_sql(operation, escape_percent=True)
        self._cur.executemany(translated, list(seq_of_parameters))
        return self

    def fetchone(self) -> DbRow | None:
        return self._wrap(self._cur.fetchone())

    def fetchall(self) -> list[DbRow]:
        names = self._column_names()
        return [DbRow(tuple(r), names) for r in self._cur.fetchall()]

    def close(self) -> None:
        self._cur.close()


class PostgresConnection:
    """Wraps a psycopg connection with the shared ``DbConnection`` surface."""

    def __init__(self, conn: "psycopg.Connection") -> None:
        self._conn = conn

    def execute(
        self,
        operation: str,
        parameters: "Sequence[Any] | dict[str, Any] | None" = None,
    ) -> _PgCursor:
        cur = self._conn.cursor()
        cur.execute(translate_sql(operation, escape_percent=True), parameters or ())
        return _PgCursor(cur)

    def executemany(
        self,
        operation: str,
        seq_of_parameters: "Iterable[Sequence[Any]]",
    ) -> _PgCursor:
        cur = self._conn.cursor()
        translated = translate_sql(operation, escape_percent=True)
        cur.executemany(translated, list(seq_of_parameters))
        return _PgCursor(cur)

    def executescript(self, script: str) -> None:
        adapted = _adapt_ddl(script)
        cur = self._conn.cursor()
        try:
            for statement in split_script(adapted):
                cur.execute(statement)
            self._conn.commit()
        finally:
            cur.close()

    def commit(self) -> None:
        self._conn.commit()

    def rollback(self) -> None:
        self._conn.rollback()

    def close(self) -> None:
        self._conn.close()

    @property
    def raw(self) -> "psycopg.Connection":
        """Expose the underlying connection for backend-specific needs."""

        return self._conn


def connect() -> PostgresConnection:
    import psycopg  # local import keeps psycopg optional at import time

    conn = psycopg.connect(settings_db_url(), autocommit=False)
    return PostgresConnection(conn)


def settings_db_url() -> str:
    """Build a libpq connection URL from the DB settings."""

    user = settings.postgres_user or "ctm"
    password = settings.postgres_password or ""
    host = settings.postgres_host or "localhost"
    port = settings.postgres_port or 5432
    name = settings.postgres_db or "ctm"
    auth = f"{user}:{password}@" if password else f"{user}@"
    return f"postgresql://{auth}{host}:{port}/{name}"

