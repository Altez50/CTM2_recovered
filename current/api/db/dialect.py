"""Backend-agnostic database introspection helpers.

These replace the SQLite-specific ``PRAGMA table_info`` and ``sqlite_master``
lookups used by :mod:`api.database` so schema introspection works across
backends.
"""

from __future__ import annotations

from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from api.db.base import DbConnection


def table_exists(connection: DbConnection, table_name: str, backend: str) -> bool:
    if backend == "sqlite":
        row = connection.execute(
            "SELECT 1 FROM sqlite_master WHERE type = 'table' AND name = ?",
            (table_name,),
        ).fetchone()
    else:
        row = connection.execute(
            """
            SELECT 1 FROM information_schema.tables
            WHERE table_schema = current_schema() AND table_name = ?
            """,
            (table_name,),
        ).fetchone()
    return row is not None


def table_columns(connection: DbConnection, table_name: str, backend: str) -> set[str]:
    if backend == "sqlite":
        return {
            str(row["name"])
            for row in connection.execute(f"PRAGMA table_info({table_name})").fetchall()
        }
    return {
        str(row["column_name"])
        for row in connection.execute(
            """
            SELECT column_name
            FROM information_schema.columns
            WHERE table_schema = current_schema() AND table_name = ?
            """,
            (table_name,),
        ).fetchall()
    }


def last_insert_id(connection: DbConnection, backend: str) -> int:
    """Return the id generated by the most recent INSERT in this session.

    SQLite: ``last_insert_rowid()``. PostgreSQL: ``lastval()`` (the value most
    recently obtained from a sequence in the current session), which is the
    closest analog when inserts use ``GENERATED BY DEFAULT AS IDENTITY``.
    """

    if backend == "sqlite":
        row = connection.execute("SELECT last_insert_rowid() AS id").fetchone()
    else:
        row = connection.execute("SELECT lastval() AS id").fetchone()
    return int(row["id"]) if row is not None else 0
